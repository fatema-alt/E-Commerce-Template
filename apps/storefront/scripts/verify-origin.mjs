import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('../src/lib/request-origin.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { fileName: 'request-origin.ts', compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} }; new Function('module', 'exports', code)(module, module.exports);
const { isStorefrontRequest } = module.exports;
const request = (origin, extra = {}, url = 'http://localhost:3000/api/shop/quote') => ({ url, headers: new Headers({ 'x-storefront-request': '1', ...(origin ? { origin } : {}), ...extra }) });
assert(isStorefrontRequest(request('https://shop.example.com'), ' https://shop.example.com/ '));
assert(isStorefrontRequest(request('http://localhost:3000'), 'http://localhost:3000/'));
assert(isStorefrontRequest(request('http://192.168.1.10:3000', {host:'192.168.1.10:3000'})));
assert(isStorefrontRequest(request('https://shop.example.com', {host:'shop.example.com', 'x-forwarded-proto':'https'})));
assert(!isStorefrontRequest(request('https://evil.example'), 'https://shop.example.com'));
assert(!isStorefrontRequest(request('https://shop.example.com', {'sec-fetch-site':'cross-site'}), 'https://shop.example.com'));
assert(!isStorefrontRequest(request('https://shop.example.com', {'x-storefront-request':''}), 'https://shop.example.com'));
assert(!isStorefrontRequest(request('http://localhost:3000'), 'invalid URL'));
assert(!isStorefrontRequest(request('null'), 'http://localhost:3000'));
assert(!isStorefrontRequest(request('http://localhost:3001'), 'http://localhost:3000'));
assert(!isStorefrontRequest(request('https://other.example', {host:'other.example'}), 'https://shop.example.com'));
assert(isStorefrontRequest(request(null), 'https://shop.example.com', true));
assert(!isStorefrontRequest(request(null), 'https://shop.example.com'));
console.log('PASS: origin normalization, public Host/protocol, LAN access, port matching, configured origin priority, CSRF and cross-site rejection');
